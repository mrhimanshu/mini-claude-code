"""Plan data model and PlanManager singleton.

A Plan is a free-form markdown document generated by the LLM in Plan Mode.
Collaborators can edit the text, delete sections, add their own text, and
annotate specific ranges.  All changes are tracked with full per-user edit
history, and annotations are anchored to character-offset ranges.
"""

from __future__ import annotations

import asyncio
import json
import uuid
from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from typing import Any


# ---------------------------------------------------------------------------
# Data classes
# ---------------------------------------------------------------------------


@dataclass
class Edit:
    """A single tracked edit operation."""

    id: str = field(default_factory=lambda: uuid.uuid4().hex[:8])
    user: str = "local"
    edit_type: str = "replace"  # "insert" | "delete" | "replace"
    offset: int = 0  # character offset in document
    old_text: str = ""  # text that was there (empty for insert)
    new_text: str = ""  # text that replaced it (empty for delete)
    created_at: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Edit:
        return cls(**{k: v for k, v in data.items() if k in cls.__dataclass_fields__})


@dataclass
class Annotation:
    """A comment anchored to a character-offset range in the document."""

    id: str = field(default_factory=lambda: uuid.uuid4().hex[:8])
    user: str = "local"
    text: str = ""
    quote: str = ""  # the selected text snippet
    range_start: int = 0  # char offset start
    range_end: int = 0  # char offset end
    resolved: bool = False
    created_at: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Annotation:
        return cls(**{k: v for k, v in data.items() if k in cls.__dataclass_fields__})


@dataclass
class Plan:
    """A free-form plan document with collaborative editing support."""

    id: str = field(default_factory=lambda: uuid.uuid4().hex[:12])
    original_content: str = ""  # immutable LLM output
    content: str = ""  # current edited content
    original_prompt: str = ""
    status: str = "draft"  # draft | shared | approved | rejected | executing
    annotations: list[Annotation] = field(default_factory=list)
    edit_history: list[Edit] = field(default_factory=list)
    created_at: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
    approved_by: list[str] = field(default_factory=list)
    rejection_reason: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "original_content": self.original_content,
            "content": self.content,
            "original_prompt": self.original_prompt,
            "status": self.status,
            "annotations": [a.to_dict() for a in self.annotations],
            "edit_history": [e.to_dict() for e in self.edit_history],
            "created_at": self.created_at,
            "approved_by": self.approved_by,
            "rejection_reason": self.rejection_reason,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Plan:
        annotations = [Annotation.from_dict(a) for a in data.pop("annotations", [])]
        edit_history = [Edit.from_dict(e) for e in data.pop("edit_history", [])]
        filtered = {k: v for k, v in data.items() if k in cls.__dataclass_fields__}
        return cls(**filtered, annotations=annotations, edit_history=edit_history)

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), indent=2)

    @classmethod
    def from_json(cls, raw: str) -> Plan:
        return cls.from_dict(json.loads(raw))


# ---------------------------------------------------------------------------
# PlanManager singleton
# ---------------------------------------------------------------------------


class PlanManager:
    """Singleton manager for the current plan.

    Provides content editing with full edit history tracking,
    range-based annotations, and approval signaling.
    """

    def __init__(self) -> None:
        self._current_plan: Plan | None = None
        self._approval_event = asyncio.Event()
        self._rejection_event = asyncio.Event()
        self._lock = asyncio.Lock()
        self._plan_updated_callbacks: list = []
        self._approval_progress_callbacks: list = []
        self._approved_users: set[str] = set()
        self._connected_users: set[str] = set()

    @property
    def current_plan(self) -> Plan | None:
        return self._current_plan

    async def set_plan(self, plan: Plan) -> None:
        """Set a new current plan and reset approval state."""
        async with self._lock:
            self._current_plan = plan
            self._approval_event.clear()
            self._rejection_event.clear()
            self._approved_users.clear()
            # CLI user ("local") is always a connected reviewer
            self._connected_users = {"local"}
        await self._notify_update()

    # -- Content editing ---------------------------------------------------

    async def update_content(
        self, new_content: str, user: str = "local", *, notify: bool = True
    ) -> None:
        """Replace the plan content wholesale, recording an edit.

        When *notify* is ``False`` the update callbacks are **not** fired.
        The WebSocket handler passes ``notify=False`` because it already
        broadcasts the change to other clients itself — firing the callback
        would cause a redundant ``plan_update`` to be sent to **all** clients
        (including the sender), which re-renders the editor and resets the
        cursor to the top of the document.
        """
        async with self._lock:
            if self._current_plan is None:
                return
            old = self._current_plan.content
            if old == new_content:
                return
            edit = Edit(
                user=user,
                edit_type="replace",
                offset=0,
                old_text=old,
                new_text=new_content,
            )
            self._current_plan.edit_history.append(edit)
            self._current_plan.content = new_content
        if notify:
            await self._notify_update()

    async def apply_edit(self, edit: Edit) -> None:
        """Apply a granular edit and adjust annotation offsets."""
        async with self._lock:
            if self._current_plan is None:
                return
            plan = self._current_plan

            # Apply the edit to content
            if edit.edit_type == "insert":
                plan.content = (
                    plan.content[: edit.offset]
                    + edit.new_text
                    + plan.content[edit.offset :]
                )
                shift = len(edit.new_text)
                self._shift_annotations(edit.offset, shift)
            elif edit.edit_type == "delete":
                end = edit.offset + len(edit.old_text)
                plan.content = plan.content[: edit.offset] + plan.content[end:]
                shift = -len(edit.old_text)
                self._shift_annotations(edit.offset, shift)
            elif edit.edit_type == "replace":
                end = edit.offset + len(edit.old_text)
                plan.content = (
                    plan.content[: edit.offset] + edit.new_text + plan.content[end:]
                )
                shift = len(edit.new_text) - len(edit.old_text)
                self._shift_annotations(edit.offset, shift)

            plan.edit_history.append(edit)
        await self._notify_update()

    def _shift_annotations(self, edit_offset: int, shift: int) -> None:
        """Shift annotation offsets after an edit. Must be called under lock."""
        if self._current_plan is None:
            return
        for ann in self._current_plan.annotations:
            if ann.range_start >= edit_offset:
                ann.range_start = max(0, ann.range_start + shift)
                ann.range_end = max(ann.range_start, ann.range_end + shift)
            elif ann.range_end > edit_offset:
                # Annotation partially overlaps the edit
                ann.range_end = max(ann.range_start, ann.range_end + shift)

    # -- Annotations -------------------------------------------------------

    async def add_annotation(self, annotation: Annotation) -> None:
        """Add a range-based annotation."""
        async with self._lock:
            if self._current_plan is None:
                return
            self._current_plan.annotations.append(annotation)
        await self._notify_update()

    async def resolve_annotation(self, annotation_id: str) -> bool:
        """Mark an annotation as resolved."""
        async with self._lock:
            if self._current_plan is None:
                return False
            for ann in self._current_plan.annotations:
                if ann.id == annotation_id:
                    ann.resolved = True
                    await self._notify_update()
                    return True
        return False

    # -- Approval ----------------------------------------------------------

    async def record_approval(self, user: str = "local") -> bool:
        """Record one user's approval.  Returns True when ALL connected
        users have approved (the plan is fully approved)."""
        fully_approved = False
        async with self._lock:
            if self._current_plan is None:
                return False
            self._approved_users.add(user)
            if user not in self._current_plan.approved_by:
                self._current_plan.approved_by.append(user)
            # Check if every connected user has approved
            if self._connected_users and self._approved_users >= self._connected_users:
                self._current_plan.status = "approved"
                fully_approved = True
        # Notify progress callbacks (for terminal display)
        await self._notify_approval_progress(user)
        if fully_approved:
            self._approval_event.set()
        return fully_approved

    async def update_connected_users(self, users: set[str]) -> bool:
        """Update the set of connected users (called by server on join/leave).
        Always includes 'local' (the CLI user).
        Returns True if the update caused full approval (e.g. a non-approver left)."""
        fully_approved = False
        async with self._lock:
            self._connected_users = users | {"local"}
            if (
                self._current_plan
                and self._connected_users
                and self._approved_users >= self._connected_users
                and not self._approval_event.is_set()
            ):
                self._current_plan.status = "approved"
                fully_approved = True
        if fully_approved:
            self._approval_event.set()
        return fully_approved

    def get_approval_status(self) -> dict[str, Any]:
        """Return current approval state for broadcasting."""
        return {
            "approved_users": sorted(self._approved_users),
            "connected_users": sorted(self._connected_users),
            "total": len(self._connected_users),
            "count": len(self._approved_users & self._connected_users),
            "all_approved": self._approval_event.is_set(),
        }

    async def reject(self, reason: str = "", user: str = "local") -> None:
        """Mark the current plan as rejected."""
        async with self._lock:
            if self._current_plan:
                self._current_plan.status = "rejected"
                self._current_plan.rejection_reason = reason
        self._rejection_event.set()

    async def wait_for_approval(self, timeout: float | None = None) -> str:
        """Wait for plan to be approved or rejected.

        Returns:
            "approved" | "rejected" | "timeout"
        """
        approval_task = asyncio.create_task(self._approval_event.wait())
        rejection_task = asyncio.create_task(self._rejection_event.wait())

        done, pending = await asyncio.wait(
            {approval_task, rejection_task},
            timeout=timeout,
            return_when=asyncio.FIRST_COMPLETED,
        )

        for task in pending:
            task.cancel()

        if approval_task in done:
            return "approved"
        elif rejection_task in done:
            return "rejected"
        return "timeout"

    # -- Approval progress callbacks ---------------------------------------

    def register_approval_progress_callback(self, callback) -> None:
        self._approval_progress_callbacks.append(callback)

    def unregister_approval_progress_callback(self, callback) -> None:
        self._approval_progress_callbacks = [
            cb for cb in self._approval_progress_callbacks if cb is not callback
        ]

    async def _notify_approval_progress(self, user: str) -> None:
        status = self.get_approval_status()
        for cb in self._approval_progress_callbacks:
            try:
                await cb(user, status)
            except Exception:
                pass

    # -- Callbacks ---------------------------------------------------------

    def register_update_callback(self, callback) -> None:
        self._plan_updated_callbacks.append(callback)

    def unregister_update_callback(self, callback) -> None:
        self._plan_updated_callbacks = [
            cb for cb in self._plan_updated_callbacks if cb is not callback
        ]

    async def _notify_update(self) -> None:
        for cb in self._plan_updated_callbacks:
            try:
                await cb()
            except Exception:
                pass

    # -- Terminal rendering ------------------------------------------------

    def render_plan_text(self) -> str:
        """Return the current plan content for terminal display."""
        if self._current_plan is None:
            return "(no plan)"
        return self._current_plan.content

    def get_clean_content(self) -> str:
        """Get the final edited plan content for LLM execution.

        Returns the plain plan text only — no annotations, no reviewer
        markers, no tracking metadata.  This is what the LLM receives.
        """
        if self._current_plan is None:
            return ""
        return self._current_plan.content


PLAN_MANAGER = PlanManager()
